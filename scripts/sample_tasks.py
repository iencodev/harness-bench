#!/usr/bin/env python3
"""Pick the task subset once, with a fixed seed, and write it to selections/.

The selection files are committed before any agent runs (pre-registration):
nobody can be accused of choosing tasks after seeing which harness wins them.

    uv run scripts/sample_tasks.py --swe-per-language 6 --tb 20 --seed 20261101
"""

import argparse
import json
import random
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SWE = ROOT / "datasets" / "swe-rebench-07-2026"
TB = ROOT / "datasets" / "terminal-bench-2-1"
OUT = ROOT / "selections"


def task_dirs(dataset: Path) -> list[Path]:
    if not dataset.is_dir():
        raise SystemExit(f"{dataset} missing; run `scripts/bench.sh download` first")
    return sorted(p for p in dataset.iterdir() if (p / "task.toml").is_file())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--swe-per-language", type=int, default=6)
    ap.add_argument("--tb", type=int, default=20)
    ap.add_argument("--seed", type=int, default=20261101)
    args = ap.parse_args()
    rng = random.Random(args.seed)
    OUT.mkdir(exist_ok=True)

    # SWE-rebench: stratified by language so no single ecosystem dominates.
    by_lang: dict[str, list[str]] = defaultdict(list)
    for d in task_dirs(SWE):
        lang = json.loads((d / "tests" / "config.json").read_text()).get("language", "?")
        by_lang[lang].append(d.name)
    swe: list[str] = []
    for lang in sorted(by_lang):
        pool = by_lang[lang]
        swe += sorted(rng.sample(pool, min(args.swe_per_language, len(pool))))
    (OUT / "swe.txt").write_text("\n".join(swe) + "\n")

    tb = sorted(rng.sample([d.name for d in task_dirs(TB)], args.tb))
    (OUT / "tb.txt").write_text("\n".join(tb) + "\n")

    (OUT / "README.md").write_text(
        "# Task selection\n\n"
        f"Generated by `scripts/sample_tasks.py --swe-per-language {args.swe_per_language} "
        f"--tb {args.tb} --seed {args.seed}`.\n\n"
        f"- `swe.txt`: {len(swe)} SWE-rebench 07-2026 tasks, "
        + ", ".join(f"{k} {min(args.swe_per_language, len(v))}" for k, v in sorted(by_lang.items()))
        + "\n"
        f"- `tb.txt`: {len(tb)} Terminal-Bench 2.1 tasks, uniform random\n\n"
        "Committed before any agent run. Do not edit by hand; re-run the script.\n"
    )
    print(f"swe: {len(swe)} tasks, tb: {len(tb)} tasks -> {OUT}")


if __name__ == "__main__":
    main()
